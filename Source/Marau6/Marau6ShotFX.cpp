// Inspection aid for Marau6.CaptureViewModel: a non-negative value freezes every shot effect at that age.
static TAutoConsoleVariable<float> CVarShotFXAge(TEXT("Marau6.ShotFXAge"), -1.f,
    TEXT("Freeze shot effects at this age in seconds; negative plays them normally."));

